# Регистронезависимый индекс: на проде один и тот же маркер встречается и как
# `vitamin_d`, и как `vitamin_D`, `fT4`/`FT4` — сравнение ключей должно это
# считать одной и той же записью.
_MARKER_LABELS_LOWER: dict[str, tuple[str, ...]] = {k.lower(): v for k, v in MARKER_LABELS.items()}


def _normalize(text: str) -> str:
    return text.lower()


def split_verified_values(values: dict[str, object], doc_text: str) -> tuple[dict[str, object], list[str]]:
    """Сверяет с `doc_text` только те ключи `values`, что есть в `MARKER_LABELS`
    (без учёта регистра). Возвращает (оставленные значения, отброшенные ключи).

    Ключ вне реестра пропускается КАК ЕСТЬ — не отбрасывается: мы не можем его
    проверить, а тихо терять реальные данные хуже, чем изредка не поймать
    экзотическую галлюцинацию неизвестного показателя (см. docstring модуля).
    `doc_text` — текст, извлечённый ИЗ ДОКУМЕНТА (PyMuPDF), а не то, что вернул
    LLM.
    """
    if not values:
        return {}, []

    haystack = _normalize(doc_text)
    kept: dict[str, object] = {}
    dropped: list[str] = []
    for key, val in values.items():
        patterns = _MARKER_LABELS_LOWER.get(str(key).lower())
        if patterns is None:
            # Неизвестный ключ — проверить нечем, оставляем как есть.
            kept[key] = val
            continue
        if any(_normalize(p) in haystack for p in patterns):
            kept[key] = val
        else:
            dropped.append(key)
    return kept, dropped
