def _normalize(text: str) -> str:
    return text.lower()


def split_verified_values(values: dict[str, object], doc_text: str) -> tuple[dict[str, object], list[str]]:
    """Оставляет только те `values`, чьё название (или известный синоним) реально
    встречается в `doc_text`. Возвращает (подтверждённые значения, отброшенные ключи).

    `doc_text` — текст, извлечённый ИЗ ДОКУМЕНТА (PyMuPDF), а не то, что вернул LLM.
    Если для ключа нет записи в `MARKER_LABELS`, используем ключ как есть (без `_`,
    в нижнем регистре) — единственный паттерн; не найден — показатель отбрасывается.
    """
    if not values:
        return {}, []

    haystack = _normalize(doc_text)
    kept: dict[str, object] = {}
    dropped: list[str] = []
    for key, val in values.items():
        patterns = MARKER_LABELS.get(key)
        if not patterns:
            patterns = (str(key).replace("_", " ").lower(),)
        if any(_normalize(p) in haystack for p in patterns):
            kept[key] = val
        else:
            dropped.append(key)
    return kept, dropped
