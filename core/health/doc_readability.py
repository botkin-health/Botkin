# core/health/doc_readability.py
"""Документный гейт: похож ли извлечённый текст документа на нормальный текст

на любом языке (issue #509).

Не зависит от `core.health.doc_marker_labels` и от реестра маркеров вообще —
именно поэтому надёжно ловит исходный инцидент: PDF, где кириллица набрана
шрифтом без соответствующих глифов (`fontname="helv"`), рендерится PyMuPDF в
текст из одних точек, цифр и разделителей — ни одного слова. Названия
показателей в таком тексте не прочитать в принципе, поэтому ни один показатель
из ответа LLM доверять нельзя, независимо от того, есть он в реестре синонимов
или нет.

Порог калибровался на двух наборах (см. `tests/test_doc_readability.py` и
отчёт issue #509):
  - «сломанный» PDF из репро #509 (точки вместо кириллицы) — доля буквенных
    символов среди непробельных 0.0, «слов» (последовательностей букв длиной
    ≥2) — 0;
  - семь читаемых E2E-бланков с реального прогона (`oak_*.pdf`, `biohimiya_*`,
    `lipidy_*`, `ttg_*`, `ferritin_*`, `vitd_*`, `kortizol_*`) — доля буквенных
    символов 0.62–0.81, слов — 17–30.

Между 0.0/0 и 0.6+/17+ большой запас, поэтому пороги (0.3 доли и 5 слов) взяты
с большим отступом в обе стороны, а не впритык к границе.
"""

from __future__ import annotations

import re

# Последовательность буквенных символов (любой алфавит) длиной от 2 — «слово».
_WORD_RE = re.compile(r"[^\W\d_]{2,}", re.UNICODE)

# Ниже этой доли буквенных символов среди непробельных — текст практически не
# содержит слов (только цифры/знаки/точки-заглушки битого шрифта).
_MIN_ALPHA_RATIO = 0.3
# И вдобавок нужно хотя бы столько отдельных «слов» — одна случайная буква
# среди цифр (артефакт OCR) не должна засчитываться как читаемый текст.
_MIN_WORD_TOKENS = 5


def _alpha_ratio(text: str) -> float:
    stripped = re.sub(r"\s+", "", text)
    if not stripped:
        return 0.0
    alpha = sum(1 for ch in stripped if ch.isalpha())
    return alpha / len(stripped)


def is_document_text_readable(text: str) -> bool:
    """True, если текст документа похож на нормальный текст (есть слова),

    а не на набор точек/цифр, оставшийся от шрифта без нужных глифов.

    Ничего не знает про биомаркеры или их названия — специально: это должно
    работать как независимый предохранитель, даже если реестр синонимов
    (`doc_marker_labels`) неполон или устарел.
    """
    if not text:
        return False
    if _alpha_ratio(text) < _MIN_ALPHA_RATIO:
        return False
    return len(_WORD_RE.findall(text)) >= _MIN_WORD_TOKENS
